#!/usr/bin/env bash
# Build Lawnchair (Graphite fork, apps/lawnchair-a17) as a release APK and install it as the ROM
# prebuilt in src/vendor/graphite/prebuilt/Lawnchair/, with a generated privapp allowlist.
# Soong re-signs it with the platform key (android_app_import, certificate: "platform").
#   tools/apps/build-lawnchair.sh [--no-build]
set -euo pipefail
G="$(cd "$(dirname "$(readlink -f "$0")")/../.." && pwd)"
L="$G/apps/lawnchair-a17"
OUT="$G/src/vendor/graphite/prebuilt/Lawnchair"
BT="$G/sdk/build-tools/37.0.0"
if [[ ${1:-} != --no-build ]]; then
    "$G/tools/apps/sdk-use-tree-framework.py"
    GRADLE_STACK=8m GRADLE_WORKERS=${GRADLE_WORKERS:-3} GRADLE_HEAP=${GRADLE_HEAP:-6g} GRADLE_LINES=5 \
        "$G/tools/testing/lawnchair-gradle.sh" :assembleLawnWithQuickstepGithubRelease
fi
apk=$(ls -t "$L"/build/outputs/apk/lawnWithQuickstepGithub/release/*.apk | head -n1)
[[ -f $apk ]] || { echo "no release APK found"; exit 1; }
"$G/tools/apps/sdk-use-tree-framework.py" --check "$apk"
pkg=$("$BT/aapt2" dump packagename "$apk")
mkdir -p "$OUT"
cp "$apk" "$OUT/Lawnchair.apk"
{
    echo '<?xml version="1.0" encoding="utf-8"?>'
    echo '<!-- Generated by tools/apps/build-lawnchair.sh: the privileged permissions Lawnchair requests -->'
    echo '<permissions>'
    echo "    <privapp-permissions package=\"$pkg\">"
    "$BT/aapt2" dump permissions "$apk" | sed -n "s/^uses-permission: name='\(android\.permission\.[A-Z_]*\)'.*/\1/p" \
        | sort -u | sed 's/.*/        <permission name="&" \/>/'
    echo '    </privapp-permissions>'
    echo '</permissions>'
} > "$OUT/privapp-permissions-lawnchair.xml"
echo "installed $apk ($pkg) → $OUT"
