#!/usr/bin/env bash
# Build Classic Power Menu (Graphite fork, apps/ClassicPowerMenu) and install it as the ROM prebuilt
# in src/vendor/graphite/prebuilt/ClassicPowerMenu/. Soong re-signs it with the platform key.
#   tools/apps/build-classic-power-menu.sh [--no-build]
set -euo pipefail
G="$(cd "$(dirname "$(readlink -f "$0")")/../.." && pwd)"
S="$G/apps/ClassicPowerMenu"
OUT="$G/src/vendor/graphite/prebuilt/ClassicPowerMenu"
if [[ ${1:-} != --no-build ]]; then
    cd "$S"
    export JAVA_HOME="$G/src/prebuilts/jdk/jdk21/linux-x86" ANDROID_HOME="$G/sdk" GRADLE_USER_HOME="$G/sdk/gradle-home"
    rc=0
    nice -n 10 bash ./gradlew --no-daemon --max-workers="${GRADLE_WORKERS:-3}" --console=plain \
        -Dorg.gradle.jvmargs="-Xmx${GRADLE_HEAP:-5g} -Dfile.encoding=UTF-8" \
        -Pkotlin.compiler.execution.strategy=in-process :app:assembleRelease \
        > "$G/logs/classic-power-menu-gradle.log" 2>&1 || rc=$?
    grep -E "^e: |error:|\* What went wrong|FAILED|BUILD (SUCCESSFUL|FAILED)" "$G/logs/classic-power-menu-gradle.log" | cut -c1-220 | tail -30
    ((rc == 0)) || exit "$rc"
fi
apk=$(ls -t "$S"/app/build/outputs/apk/release/*.apk | head -n1)
[[ -f $apk ]] || { echo "no release APK found"; exit 1; }
mkdir -p "$OUT"
cp "$apk" "$OUT/ClassicPowerMenu.apk"
{
    echo '<?xml version="1.0" encoding="utf-8"?>'
    echo '<!-- Generated by tools/apps/build-classic-power-menu.sh: the privileged permissions Classic Power Menu requests -->'
    echo '<permissions>'
    echo '    <privapp-permissions package="com.kieronquinn.app.classicpowermenu">'
    "$G/sdk/build-tools/37.0.0/aapt2" dump permissions "$OUT/ClassicPowerMenu.apk" | sed -n "s/^uses-permission: name='\(android\.permission\.[A-Z_]*\)'.*/\1/p" \
        | sort -u | sed 's/.*/        <permission name="&" \/>/'
    echo '    </privapp-permissions>'
    echo '</permissions>'
} > "$OUT/privapp-permissions-classicpowermenu.xml"
echo "installed $apk -> $OUT"
