#!/usr/bin/env bash
# Build Graphite's 3D wallpaper (apps/GraphiteDepthWallpaper) and install it as the ROM prebuilt in
# src/vendor/graphite/prebuilt/DepthWallpaper/, with a generated privapp allowlist. Soong re-signs it with the
# platform key. The models (Apache-2.0) aren't in git: they're downloaded here at pinned revisions and checked.
#   tools/apps/build-depth-wallpaper.sh [--no-build]
set -euo pipefail
G="$(cd "$(dirname "$(readlink -f "$0")")/../.." && pwd)"
A="$G/apps/GraphiteDepthWallpaper"
OUT="$G/src/vendor/graphite/prebuilt/DepthWallpaper"
BT="$G/sdk/build-tools/37.0.0"
HF=https://huggingface.co
DEPTH_REV=4472b7362082ad9968fee890ca0f1e5aca36b93d
SAM_REV=5850ab45f587c112167512ffef949107115e26a0

model() {  # file, url, sha256
    local f="$A/models/$1"
    if [[ ! -f $f ]] || ! echo "$3  $f" | sha256sum -c --status; then
        mkdir -p "$A/models"
        curl -sfL -o "$f.tmp" "$2"
        echo "$3  $f.tmp" | sha256sum -c --status || { echo "wrong checksum for $1"; rm -f "$f.tmp"; exit 1; }
        mv "$f.tmp" "$f"
    fi
}
model depth.onnx "$HF/onnx-community/depth-anything-v2-small/resolve/$DEPTH_REV/onnx/model_quantized.onnx" \
    fcf51f1b230362b28690bb9d1809bf0431f29cad20534e3f589bd7285547f20d
model sam_encoder.onnx "$HF/Xenova/slimsam-77-uniform/resolve/$SAM_REV/onnx/vision_encoder.onnx" \
    9f8433273a6750b587779baa0cf5508111001bf7e7acfcf585d370139fd366d0
model sam_decoder.onnx "$HF/Xenova/slimsam-77-uniform/resolve/$SAM_REV/onnx/prompt_encoder_mask_decoder.onnx" \
    f4514391764fbd56e08e119060d874ecd7d52994bfb1968af159e12d4943b5bb

if [[ ${1:-} != --no-build ]]; then
    (cd "$A" && bash ./gradlew --no-daemon :app:assembleRelease)
fi
apk="$A/app/build/outputs/apk/release/app-release.apk"
[[ -f $apk ]] || { echo "no release APK found"; exit 1; }
pkg=$("$BT/aapt2" dump packagename "$apk")
mkdir -p "$OUT"
cp "$apk" "$OUT/DepthWallpaper.apk"
{
    echo '<?xml version="1.0" encoding="utf-8"?>'
    echo '<!-- Generated by tools/apps/build-depth-wallpaper.sh: the privileged permissions the 3D wallpaper requests -->'
    echo '<permissions>'
    echo "    <privapp-permissions package=\"$pkg\">"
    "$BT/aapt2" dump permissions "$apk" | sed -n "s/^uses-permission: name='\(android\.permission\.[A-Z_]*\)'.*/\1/p" \
        | sort -u | sed 's/.*/        <permission name="&" \/>/'
    echo '    </privapp-permissions>'
    echo '</permissions>'
} > "$OUT/privapp-permissions-depthwallpaper.xml"
echo "installed $apk ($pkg) → $OUT"
