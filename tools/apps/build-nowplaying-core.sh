#!/usr/bin/env bash
# Build Graphite Now Playing (the core, org.graphite.nowplaying) and its database downloader (org.graphite.musicdb)
# from apps/AmbientMusicMod (github.com/bjakra/AmbientMusicMod, branch graphite) and install them as ROM prebuilts in
# src/vendor/graphite/prebuilt/GraphiteNowPlaying/, with a generated privapp allowlist for the core.
# The newest music database (Kieron Quinn's AmbientMusicManifest, as AMM checks it) becomes the default, so a new
# install starts with the database current at build time. Soong re-signs both with the platform key.
#   tools/apps/build-nowplaying-core.sh [--no-build]
set -euo pipefail
G="$(cd "$(dirname "$(readlink -f "$0")")/../.." && pwd)"
A="$G/apps/AmbientMusicMod"
OUT="$G/src/vendor/graphite/prebuilt/GraphiteNowPlaying"
BT="$G/sdk/build-tools/37.0.0"

if [[ ${1:-} != --no-build ]]; then
    manifest=$(curl -fsS https://raw.githubusercontent.com/KieronQuinn/AmbientMusicManifest/main/release_v3.json \
        | python3 -c 'import json, sys; print(json.load(sys.stdin)["url"])')
    echo "default database: $manifest"
    printf 'sdk.dir=%s/sdk\nstoreFile=%s/.android/debug.keystore\nkeyAlias=androiddebugkey\nstorePassword=android\nkeyPassword=android\n' \
        "$G" "$HOME" > "$A/local.properties"
    (cd "$A" && bash ./gradlew --no-daemon -q -PgraphiteManifestV3="$manifest" \
        :app:assembleRelease :musicdb:assembleRelease)
fi
core="$A/app/build/outputs/apk/release/app-release.apk"
musicdb="$A/musicdb/build/outputs/apk/release/musicdb-release.apk"
mkdir -p "$OUT"
cp "$core" "$OUT/GraphiteNowPlaying.apk"
cp "$musicdb" "$OUT/GraphiteMusicDb.apk"
pkg=$("$BT/aapt2" dump packagename "$core")
{
    echo '<?xml version="1.0" encoding="utf-8"?>'
    echo '<!-- Generated by tools/apps/build-nowplaying-core.sh: the privileged permissions Graphite Now Playing requests -->'
    echo '<permissions>'
    echo "    <privapp-permissions package=\"$pkg\">"
    "$BT/aapt2" dump permissions "$core" | sed -n "s/^uses-permission: name='\(android\.permission\.[A-Z_]*\)'.*/\1/p" \
        | sort -u | sed 's/.*/        <permission name="&" \/>/'
    echo '    </privapp-permissions>'
    echo '</permissions>'
} > "$OUT/privapp-permissions-nowplaying.xml"
echo "installed $pkg and org.graphite.musicdb → $OUT"
